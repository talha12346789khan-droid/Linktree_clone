export default async function Page({ params }) {
  const { handle } = await params;
  const client = await clientPromise
  const db = client.db("bittree")
  const collection = db.collection("links")

  // Case-insensitive search for handle
  const item = await collection.findOne({ 
    handle: { $regex: `^${handle}$`, $options: "i" } 
  })
  if (!item) {
    notFound()
  }

  return (
    <div className="flex flex-1 justify-center bg-gradient-to-br from-cyan-800 to-cyan-900 p-4 md:p-6">
      <div className="photo gap-4 flex justify-center items-center flex-col w-full max-w-md py-8 md:py-0">
       {item.picture &&( <img
          className="rounded-full my-4 md:my-5 w-32 h-32 md:w-40 md:h-40 object-cover border-4 border-white shadow-lg" 
          src={item.picture}
          alt={`${item.handle} profile`}
        />)}

        <span className="font-bold my-6 md:my-10 text-white text-xl md:text-2xl text-center">
          @{item.handle}
        </span>
        <div className="links w-full">
          {item.links && item.links.length > 0 ? (
            item.links.map((linkItem, index) => {
              const icon = getLinkIconSVG(linkItem.name)
              return <Link href={linkItem.url} key={index} target="_blank" rel="noopener noreferrer"><div className="py-3 md:py-4 shadow-lg my-2 md:my-3 px-4 bg-slate-700 hover:bg-slate-600 rounded-lg text-white flex items-center gap-3 justify-center transition transform hover:scale-105 w-full text-sm md:text-base">
                <div className="flex-shrink-0">{icon}</div>
                <span>{linkItem.name}</span>
              </div></Link>
            })
          ) : (
            <div className="py-4 text-center text-gray-300">
              <p>No links added yet</p>
            </div>
          )}
        </div>
      </div>
    </div>
  )
}
